-- Receipt hash: split rows may share a hash only inside one split group.
-- ---------------------------------------------------------------------------

create or replace function public.enforce_receipt_hash_uniqueness()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  existing_id uuid;
  existing_created timestamptz;
begin
  perform pg_advisory_xact_lock(
    hashtextextended(new.project_id::text || ':' || new.receipt_file_hash, 0)
  );

  select e.id, e.created_at
    into existing_id, existing_created
  from public.expenses e
  where e.project_id = new.project_id
    and e.receipt_file_hash = new.receipt_file_hash
    and e.id is distinct from new.id
    and (
      e.split_group_id is distinct from new.split_group_id
      or (e.split_group_id is null and new.split_group_id is null)
    )
  limit 1;

  if found then
    raise exception 'Duplicate receipt — already uploaded on %',
      to_char(existing_created at time zone 'UTC', 'YYYY-MM-DD')
      using
        errcode = '23505',
        detail = existing_id::text;
  end if;

  return new;
end;
$$;

create or replace function public.prevent_expense_invoice_relink()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  existing_number text;
begin
  if old.invoice_id is not null
     and new.invoice_id is not null
     and old.invoice_id is distinct from new.invoice_id then
    select i.invoice_number
      into existing_number
    from public.invoices i
    where i.id = old.invoice_id;

    raise exception 'This expense is already on invoice %',
      coalesce(existing_number, old.invoice_id::text)
      using errcode = '23514';
  end if;

  return new;
end;
$$;

create or replace function public.log_expense_changes()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  col text;
  old_json jsonb := to_jsonb(old);
  new_json jsonb := to_jsonb(new);
  tracked text[] := array[
    'category_id',
    'vendor',
    'expense_date',
    'amount',
    'receipt_number',
    'description',
    'payment_method',
    'invoice_id',
    'verification_status',
    'duplicate_of'
  ];
begin
  foreach col in array tracked loop
    if old_json -> col is distinct from new_json -> col then
      insert into public.expense_audit (
        expense_id,
        changed_by,
        field,
        old_value,
        new_value
      )
      values (
        new.id,
        auth.uid(),
        col,
        old_json ->> col,
        new_json ->> col
      );
    end if;
  end loop;

  return new;
end;
$$;

-- subtotal = verified linked expenses
-- builder_fee = round(subtotal * builder_fee_percent / 100, 2)
-- retainage = round((subtotal + builder_fee) * retainage_percent / 100, 2)
-- total_amount is the figure printed on the invoice and is left unchanged.
create or replace function public.recalculate_invoice(target uuid)
returns void
language plpgsql
set search_path = public
as $$
declare
  spent numeric(12, 2);
  fee_pct numeric;
  ret_pct numeric;
  fee numeric(12, 2);
  ret numeric(12, 2);
begin
  if target is null
     or current_setting('app.skip_invoice_refresh', true) = 'on' then
    return;
  end if;

  select coalesce(sum(e.amount), 0)
    into spent
  from public.expenses e
  where e.invoice_id = target
    and e.verification_status = 'verified';

  select p.builder_fee_percent, p.retainage_percent
    into fee_pct, ret_pct
  from public.invoices i
  join public.projects p on p.id = i.project_id
  where i.id = target;

  if not found then
    return;
  end if;

  fee := round(spent * fee_pct / 100, 2);
  ret := round((spent + fee) * ret_pct / 100, 2);

  update public.invoices
  set
    subtotal = spent,
    builder_fee = fee,
    retainage = ret
  where id = target
    and (
      subtotal is distinct from spent
      or builder_fee is distinct from fee
      or retainage is distinct from ret
    );
end;
$$;

create or replace function public.touch_invoice_amounts()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if current_setting('app.skip_invoice_refresh', true) = 'on' then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  if tg_op = 'DELETE' then
    perform public.recalculate_invoice(old.invoice_id);
    return old;
  end if;

  if tg_op = 'UPDATE' and old.invoice_id is distinct from new.invoice_id then
    perform public.recalculate_invoice(old.invoice_id);
  end if;

  perform public.recalculate_invoice(new.invoice_id);
  return new;
end;
$$;

create or replace function public.refresh_project_invoice_amounts()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  inv uuid;
begin
  if new.builder_fee_percent is distinct from old.builder_fee_percent
     or new.retainage_percent is distinct from old.retainage_percent then
    for inv in
      select i.id
      from public.invoices i
      where i.project_id = new.id
    loop
      perform public.recalculate_invoice(inv);
    end loop;
  end if;

  return new;
end;
$$;

-- Null expense links before the invoice row is removed so the refresh
-- trigger does not update a row that is mid-delete.
create or replace function public.unlink_invoice_expenses()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  perform set_config('app.skip_invoice_refresh', 'on', true);
  update public.expenses
  set invoice_id = null
  where invoice_id = old.id;
  perform set_config('app.skip_invoice_refresh', 'off', true);
  return old;
end;
$$;

