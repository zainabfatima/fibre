-- Fibre Construction: projects, receipts, invoices.
-- Money columns are numeric so totals are summed in SQL, not JavaScript floats.
-- Receipt files: receipts bucket, {project_id}/{expense_id}.jpg
-- Thumbnails: receipts bucket, {project_id}/thumbs/{expense_id}.jpg
-- Invoice files: invoices bucket, {project_id}/{invoice_id}

create extension if not exists pg_trgm with schema extensions;

