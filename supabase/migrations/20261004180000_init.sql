create table public.projects (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  address text,
  client_name text,
  client_email text,
  builder_fee_percent numeric not null default 15,
  retainage_percent numeric not null default 0,
  status text not null default 'active',
  contract_amount numeric(12, 2),
  share_token text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint projects_name_not_blank check (char_length(trim(name)) > 0),
  constraint projects_status_check check (status in ('active', 'completed', 'on_hold')),
  constraint projects_builder_fee_percent_range check (
    builder_fee_percent >= 0 and builder_fee_percent <= 100
  ),
  constraint projects_retainage_percent_range check (
    retainage_percent >= 0 and retainage_percent <= 100
  ),
  constraint projects_share_token_key unique (share_token)
);

create table public.categories (
  id integer generated by default as identity primary key,
  code integer not null,
  name text not null,
  sort_order integer not null,
  is_active boolean not null default true,
  keywords text[] not null default '{}',
  constraint categories_code_key unique (code),
  constraint categories_code_positive check (code > 0),
  constraint categories_name_not_blank check (char_length(trim(name)) > 0)
);

create table public.project_budgets (
  project_id uuid not null references public.projects (id) on delete cascade,
  category_id integer not null references public.categories (id) on delete restrict,
  budget_amount numeric(12, 2) not null,
  constraint project_budgets_pkey primary key (project_id, category_id),
  constraint project_budgets_amount_nonnegative check (budget_amount >= 0)
);

create table public.invoices (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects (id) on delete cascade,
  invoice_number text not null,
  invoice_date date not null default current_date,
  subtotal numeric(12, 2) not null default 0,
  builder_fee numeric(12, 2) not null default 0,
  retainage numeric(12, 2) not null default 0,
  total_amount numeric(12, 2) not null default 0,
  status text not null default 'pending',
  amount_paid numeric(12, 2) not null default 0,
  paid_date date,
  file_path text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint invoices_project_number_key unique (project_id, invoice_number),
  constraint invoices_number_not_blank check (char_length(trim(invoice_number)) > 0),
  constraint invoices_status_check check (
    status in ('pending', 'paid', 'partially_paid', 'void')
  ),
  constraint invoices_amount_paid_nonnegative check (amount_paid >= 0)
);

comment on column public.invoices.subtotal is
  'Sum of linked verified expenses. Maintained by recalculate_invoice().';
comment on column public.invoices.total_amount is
  'Amount written on the invoice document. Not overwritten by recalculate_invoice().';
comment on column public.invoices.file_path is
  'Storage path in the invoices bucket.';

create table public.expenses (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects (id) on delete cascade,
  category_id integer references public.categories (id) on delete restrict,
  vendor text,
  expense_date date,
  amount numeric(12, 2) not null default 0,
  receipt_number text,
  description text,
  payment_method text,
  receipt_file_path text not null,
  receipt_file_hash text not null,
  receipt_thumbnail_path text,
  split_group_id uuid,
  invoice_id uuid references public.invoices (id) on delete set null,
  ai_extracted jsonb,
  ai_suggested_category_ids integer[],
  ai_confidence numeric,
  verification_status text not null default 'needs_review',
  duplicate_of uuid references public.expenses (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users (id) on delete set null,
  constraint expenses_verification_status_check check (
    verification_status in ('needs_review', 'verified', 'flagged')
  ),
  constraint expenses_ai_confidence_range check (
    ai_confidence is null or (ai_confidence >= 0 and ai_confidence <= 1)
  ),
  constraint expenses_receipt_hash_sha256 check (receipt_file_hash ~ '^[0-9a-f]{64}$'),
  constraint expenses_duplicate_not_self check (
    duplicate_of is null or duplicate_of <> id
  ),
  constraint expenses_verified_requires_fields check (
    verification_status <> 'verified'
    or (
      category_id is not null
      and expense_date is not null
      and vendor is not null
      and char_length(trim(vendor)) > 0
    )
  )
);

